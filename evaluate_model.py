def generate_benign_traffic(n: int = 300) -> pd.DataFrame:
    """
    Simulate institutional / exchange-level normal transactions.

    Characteristics:
    - 1-3 inputs, 1-2 outputs
    - Moderate, round-ish amounts (exchange settlements)
    - Standard ports (8333, 443)
    - Low fee rate (sub-satoshi urgency)
    - Geo-diverse but ASN-coherent (major cloud ASNs)
    """
    records = []
    for _ in range(n):
        n_in  = int(_rng.integers(1, 4))
        n_out = int(_rng.integers(1, 3))
        in_addrs  = [_btc_addr("bc1q") for _ in range(n_in)]
        out_addrs = [_btc_addr("bc1q") for _ in range(n_out)]
        total     = round(float(_rng.uniform(0.1, 10.0)), 6)
        in_amts   = [round(total / n_in, 8)] * n_in
        out_amts  = [round(total * 0.99 / n_out, 8)] * n_out
        fee       = round(total * 0.001, 8)
        records.append({
            "timestamp":        _ts(),
            "txid":             fake.sha256(),
            "src_ip":           _src_ip(),
            "dst_ip":           _src_ip(),
            "src_port":         int(_rng.choice([8333, 443, 8332])),
            "dst_port":         int(_rng.choice([8333, 18333])),
            "input_addresses":  _pipe(in_addrs),
            "output_addresses": _pipe(out_addrs),
            "input_amounts":    _pipe(in_amts),
            "output_amounts":   _pipe(out_amts),
            "fee":              fee,
            "script_type":      "P2WPKH",
            "geo_country":      fake.country_code(),
            "asn":              f"AS{int(_rng.integers(1000, 65000))}",
            "_label":           0,  # BENIGN
        })
    return pd.DataFrame(records)


