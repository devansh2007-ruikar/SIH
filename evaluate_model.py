_PASS_THRESH = {
    "precision": 0.70,
    "recall":    0.65,
    "f1_score":  0.65,
    "fpr":       0.20,   # FPR must be BELOW this threshold
}


def _fmt_metric(name: str, value: float) -> str:
    if np.isnan(value):
        return _c("  N/A (single-class dataset)", _GREY)

    thresh = _PASS_THRESH.get(name)
    if thresh is None:
        return f"  {value:.4f}"

    passed = (value <= thresh) if name == "fpr" else (value >= thresh)
    colour = _GREEN if passed else _RED
    marker = "PASS" if passed else "FAIL"
    return _c(f"  {value:.4f}  [{marker}]  threshold: {thresh:.2f}", colour)


