class ModelEvaluator:
    """
    Trains an IsolationForest on a combined benign + threat corpus,
    then measures per-dataset and aggregate forensic metrics.
    """

    def __init__(
        self,
        n_estimators: int = 200,
        contamination: float = 0.10,
        random_state: int = _SEED,
        verbose: bool = False,
    ) -> None:
        self.n_estimators  = n_estimators
        self.contamination = contamination
        self.random_state  = random_state
        self.verbose       = verbose
        self.model: IsolationForest | None = None
        self._feature_cols: List[str] = []

    def fit(self, X_train: pd.DataFrame) -> None:
        """Train the IsolationForest on the given feature matrix."""
        self.model = IsolationForest(
            n_estimators=self.n_estimators,
            contamination=self.contamination,
            random_state=self.random_state,
            n_jobs=-1,
        )
        self._feature_cols = list(X_train.columns)
        self.model.fit(X_train[self._feature_cols])

    def _predict_timed(self, X: pd.DataFrame) -> Tuple[np.ndarray, float]:
        """
        Return (predictions_array, median_processing_time_us).
        Predictions: +1 = normal, -1 = anomaly -> flip to 1 = threat.
        """
        times = []
        preds = []
        X_vals = X[self._feature_cols].values
        for i in range(len(X_vals)):
            row = X_vals[i : i + 1]
            t0  = time.perf_counter_ns()
            p   = self.model.predict(row)[0]
            t1  = time.perf_counter_ns()
            preds.append(0 if p == 1 else 1)
            times.append((t1 - t0) / 1_000.0)  # ns -> us

        return np.array(preds, dtype=int), float(np.median(times))

    def evaluate_dataset(
        self,
        name: str,
        df: pd.DataFrame,
        true_labels: np.ndarray,
    ) -> Dict:
        """
        Run evaluation for a single named dataset and return a metrics dict.
        """
        assert self.model is not None, "Call fit() before evaluate_dataset()"

        X = build_features(df)
        for col in self._feature_cols:
            if col not in X.columns:
                X[col] = 0.0
        X = X[self._feature_cols].fillna(0.0)

        tracemalloc.start()
        pred_labels, median_us = self._predict_timed(X)
        _current, peak_bytes = tracemalloc.get_traced_memory()
        tracemalloc.stop()
        peak_mb = peak_bytes / (1024 ** 2)

        n_pos = int(true_labels.sum())
        n_neg = len(true_labels) - n_pos

        if n_pos == 0 or n_neg == 0:
            prec = rec = f1 = fpr = float("nan")
        else:
            prec = precision_score(true_labels, pred_labels, zero_division=0)
            rec  = recall_score(true_labels, pred_labels, zero_division=0)
            f1   = f1_score(true_labels, pred_labels, zero_division=0)
            tn, fp, fn, tp = confusion_matrix(
                true_labels, pred_labels, labels=[0, 1]
            ).ravel()
            fpr = fp / (fp + tn) if (fp + tn) > 0 else 0.0

        return {
            "dataset":        name,
            "n_total":        len(df),
            "n_threats":      n_pos,
            "n_benign":       n_neg,
            "precision":      prec,
            "recall":         rec,
            "f1_score":       f1,
            "fpr":            fpr,
            "median_time_us": median_us,
            "peak_mem_mb":    peak_mb,
            "pred_labels":    pred_labels,
            "true_labels":    true_labels,
        }


