def generate_known_threats(n: int = 300) -> pd.DataFrame:
    """
    Simulate threat vectors the model WAS trained to detect:
    multi-hop peel chains, CoinJoin mixers, fee-spike hops.
    """
    records: List[Dict] = []
    per_type = max(1, n // 3)

    # 2a. Multi-hop peel chains
    for _ci in range(per_type):
        depth  = int(_rng.integers(3, 6))
        amount = round(float(_rng.uniform(0.5, 5.0)), 6)
        prev   = _btc_addr("bc1q")
        for hop in range(depth):
            next_addr = _btc_addr("bc1q")
            peel      = round(amount * 0.001, 8)
            amount   -= peel + 0.00001
            records.append({
                "timestamp":        _ts(),
                "txid":             fake.sha256(),
                "src_ip":           _src_ip(),
                "dst_ip":           _src_ip(),
                "src_port":         int(_rng.choice([9050, 9150])),
                "dst_port":         8333,
                "input_addresses":  prev,
                "output_addresses": _pipe([next_addr, _btc_addr("bc1q")]),
                "input_amounts":    str(round(amount + peel + 0.00001, 8)),
                "output_amounts":   _pipe([round(amount, 8), peel]),
                "fee":              round(0.00001 * (hop + 1), 8),
                "script_type":      "P2WPKH",
                "geo_country":      fake.country_code(),
                "asn":              f"AS{int(_rng.integers(1000, 65000))}",
                "_label":           1,
            })
            prev = next_addr
        if len(records) >= n:
            break

    # 2b. CoinJoin mixers
    for _ in range(min(per_type, n - len(records))):
        n_par = int(_rng.integers(10, 20))
        equal = round(float(_rng.uniform(0.01, 0.5)), 4)
        records.append({
            "timestamp":        _ts(),
            "txid":             fake.sha256(),
            "src_ip":           _src_ip(),
            "dst_ip":           _src_ip(),
            "src_port":         9050,
            "dst_port":         8333,
            "input_addresses":  _pipe([_btc_addr("1") for _ in range(n_par)]),
            "output_addresses": _pipe([_btc_addr("bc1q") for _ in range(n_par)]),
            "input_amounts":    _pipe([equal] * n_par),
            "output_amounts":   _pipe([equal] * n_par),
            "fee":              round(0.0001 * n_par, 8),
            "script_type":      "P2SH",
            "geo_country":      fake.country_code(),
            "asn":              f"AS{int(_rng.integers(1000, 65000))}",
            "_label":           1,
        })

    # 2c. Fee spike urgency hops
    for _ in range(min(per_type, n - len(records))):
        total = round(float(_rng.uniform(0.05, 1.0)), 6)
        fee   = round(total * 0.30, 8)
        records.append({
            "timestamp":        _ts(),
            "txid":             fake.sha256(),
            "src_ip":           _src_ip(),
            "dst_ip":           _src_ip(),
            "src_port":         int(_rng.choice([9050, 4444])),
            "dst_port":         8333,
            "input_addresses":  _btc_addr("bc1p"),
            "output_addresses": _btc_addr("bc1q"),
            "input_amounts":    str(total),
            "output_amounts":   str(round(total - fee, 8)),
            "fee":              fee,
            "script_type":      "P2TR",
            "geo_country":      fake.country_code(),
            "asn":              f"AS{int(_rng.integers(1000, 65000))}",
            "_label":           1,
        })

    return pd.DataFrame(records[:n])


