def _count_pipe(s) -> int:
    if not s or str(s).strip() in ("", "nan"):
        return 0
    return len([t for t in str(s).split("|") if t.strip()])


def _sum_pipe(s) -> float:
    if not s or str(s).strip() in ("", "nan"):
        return 0.0
    total = 0.0
    for t in str(s).split("|"):
        try:
            total += float(t.strip())
        except ValueError:
            pass
    return total


def _build_features_lightweight(df: pd.DataFrame) -> pd.DataFrame:
    """
    Lightweight feature extraction that does NOT require the full
    ml_engine graph pipeline. Used as a safe fallback for evaluation.

    Features (8):
    - fan_in, fan_out          : input/output address counts
    - total_amount             : sum of input amounts
    - fee_rate                 : fee / max(total_amount, 1e-9)
    - port_risk                : 1.0 if Tor/I2P port, else 0.0
    - equal_output_ratio       : fraction of outputs within 1% of mode
    - amount_diversity         : std-dev of output amounts (normalised)
    - io_ratio                 : fan_out / max(fan_in, 1)
    """
    TOR_I2P = {9050, 9051, 9150, 4444}

    feats = pd.DataFrame({
        "fan_in":       df["input_addresses"].apply(_count_pipe),
        "fan_out":      df["output_addresses"].apply(_count_pipe),
        "total_amount": df["input_amounts"].apply(_sum_pipe),
        "fee":          pd.to_numeric(df["fee"], errors="coerce").fillna(0.0),
        "port_risk":    df["src_port"].apply(
            lambda p: 1.0 if int(p) in TOR_I2P else 0.0
        ),
    })

    feats["fee_rate"] = feats["fee"] / feats["total_amount"].clip(lower=1e-9)
    feats["io_ratio"] = feats["fan_out"] / feats["fan_in"].clip(lower=1)

    def _equal_ratio(s) -> float:
        vals = []
        for t in str(s).split("|"):
            try:
                vals.append(float(t.strip()))
            except ValueError:
                pass
        if len(vals) < 2:
            return 0.0
        mode_val = max(
            set(round(v, 4) for v in vals),
            key=lambda v: sum(
                1 for x in vals if abs(x - v) / max(abs(v), 1e-9) < 0.01
            ),
        )
        equal_count = sum(
            1 for x in vals
            if abs(x - mode_val) / max(abs(mode_val), 1e-9) < 0.01
        )
        return equal_count / len(vals)

    feats["equal_output_ratio"] = df["output_amounts"].apply(_equal_ratio)

    def _amt_std(s) -> float:
        vals = []
        for t in str(s).split("|"):
            try:
                vals.append(float(t.strip()))
            except ValueError:
                pass
        if len(vals) < 2:
            return 0.0
        arr = np.array(vals)
        return float(np.std(arr) / max(np.mean(arr), 1e-9))

    feats["amount_diversity"] = df["output_amounts"].apply(_amt_std)
    return feats.fillna(0.0)


def build_features(df: pd.DataFrame) -> pd.DataFrame:
    """
    Attempt to use the full MITHYA ml_engine feature pipeline.
    Falls back to lightweight extraction if ml_engine is unavailable.
    """
    if _HAS_ENGINE:
        try:
            adapter = BitcoinCSVAdapter()
            df2 = adapter.normalize_addresses(df.copy())
            if not pd.api.types.is_datetime64_any_dtype(df2["timestamp"]):
                df2["timestamp"] = pd.to_datetime(df2["timestamp"], errors="coerce")
            feats, _ = engineer_features(df2)
            return feats.fillna(0.0)
        except Exception:
            pass
    return _build_features_lightweight(df)


