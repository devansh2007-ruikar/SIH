def _btc_addr(prefix: str = "bc1q") -> str:
    """Generate a plausible-looking Bitcoin address."""
    chars = "0123456789abcdefghjklmnpqrstuvwxyz"
    tail  = "".join(_rng.choice(list(chars)) for _ in range(38))
    return f"{prefix}{tail}"


def _pipe(items: List) -> str:
    return "|".join(str(i) for i in items)


def _ts() -> str:
    return fake.date_time_between(start_date="-30d", end_date="now").isoformat(sep=" ")


def _src_ip() -> str:
    return fake.ipv4_public()


