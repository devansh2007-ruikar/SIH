"""
evaluate_model.py -- ML Validation & Benchmarking Suite
========================================================

Principal ML Security Engineer / Forensic Architect evaluation harness
for MITHYA's Isolation Forest anomaly detection engine.

Metrics Reported
----------------
- Precision, Recall, F1-Score (computed from pseudo-labels)
- False-Positive Rate (FPR) -- critical for operational deployments
- Median per-transaction Processing Time (us)
- Peak Memory Usage (MB via tracemalloc)

Dataset Categories
------------------
1. benign_traffic   -- exchanges & high-volume institutional transfers
2. known_threats    -- multi-hop peel chains, CoinJoin mixers, fee spikes
3. novel_threats    -- structurally novel obfuscation (fan-out, port reuse,
                       micro-dust dispersal) NOT seen in training distribution

Methodology
-----------
IsolationForest is an *unsupervised* model. To compute supervised metrics we
use *pseudo-labels*: transactions generated by each category are assigned a
ground-truth binary label (0 = benign, 1 = threat). The model is trained on a
combined corpus (simulating production deployment) and we measure its ability
to correctly flag threats vs. noise.

This mirrors real forensic validation practice (red-team / blue-team
classification against a labelled holdout set generated by the same synthetic
adversarial framework).

Usage
-----

    python evaluate_model.py
    python evaluate_model.py --records 500 --contamination 0.10 --verbose

"""

